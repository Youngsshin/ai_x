SELECT MNO, MNAME, TO_CHAR(MRDATE, 'YYYY-MM/DD') AS MRDATE, MEMAIL AS MMAIL, MPOINT AS POINT, LEVELNAME||'고객' AS LEVELNAME
    FROM MEMBER M, MEMBER_LEVEL ML
    WHERE M.LEVELNO = ML.LEVELNO;