-- 연습문제
DROP TABLE MEMBER;
DROP TABLE MEMBER_LEVEL;
DROP SEQUENCE MEMBER_MNO_SQ;
CREATE TABLE MEMBER_LEVEL(
    LEVELNO NUMBER(2),
    LEVELNAME VARCHAR2(30) NOT NULL,
    PRIMARY KEY(LEVELNO)
);
CREATE TABLE MEMBER(
    mNO NUMBER(3),
    mNAME VARCHAR2(200) NOT NULL,
    mPW VARCHAR2(50) NOT NULL,
    mEMAIL VARCHAR2(250),
    mPOINT NUMBER(5),
    mRDATE DATE DEFAULT SYSDATE,
    LEVELNO NUMBER(2),
    PRIMARY KEY(mNO),
    CHECK(mPOINT>=0),
    FOREIGN KEY (LEVELNO) REFERENCES MEMBER_LEVEL (LEVELNO)
);
CREATE SEQUENCE MEMBER_MNO_SQ
    MAXVALUE 999
    NOCACHE NOCYCLE;
